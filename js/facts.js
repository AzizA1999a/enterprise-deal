(function () {
  var F = window.B2B_FACTS, cfg = window.B2B_CONFIG || {};
  function esc(s) { return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]; }); }
  function fact(f) {
    return '<div class="d-fact">' + (f.n ? '<div class="n num">' + esc(f.n) + "</div>" : "") + '<div class="t">' + esc(f.t) + "</div>" +
      (f.src ? '<div class="d-src">' + esc(f.src) + "</div>" : "") + "</div>";
  }
  Object.keys(F).forEach(function (k) {
    var el = document.getElementById("fact-" + k);
    if (!el || !Array.isArray(F[k])) return;
    el.innerHTML = F[k].length ? F[k].map(fact).join("") : '<div class="d-empty">Research for this slide has not been added yet.</div>';
  });
  var c = document.getElementById("case-body");
  if (c) {
    var cs = F.caseStudy;
    c.innerHTML = !cs ? '<div class="d-empty" style="margin-top:1rem">A real case has not been added yet.</div>' :
      '<div class="d-h" style="margin:0.5rem 0 1.2rem">' + esc(cs.title) + '</div><div class="d-cols top wide-l" style="flex:1"><ul class="d-list">' +
      cs.points.map(function (p, i) { return '<li class="step"><i>' + (i + 1) + "</i><span>" + esc(p.t) + (p.s ? "<small>" + esc(p.s) + "</small>" : "") + "</span></li>"; }).join("") +
      '</ul><div style="display:flex;flex-direction:column;gap:1rem"><div class="d-art" style="height:15rem"><img src="art/door-pilot.jpg" alt=""></div><div class="d-fact step"><div class="t" style="font-size:1.35rem">' + esc(cs.lesson) + '</div></div><div class="grow"></div><div class="d-src">' + esc(cs.src) + "</div></div></div>";
  }
  var s = document.getElementById("sources");
  if (s) s.innerHTML = F.sources.length ? F.sources.map(function (x) { return "<li>" + esc(x) + "</li>"; }).join("") : "<li>Sources will be listed here.</li>";
  Array.prototype.forEach.call(document.querySelectorAll("[data-team]"), function (el) {
    el.innerHTML = (cfg.team || []).map(function (n) { return "<span>" + esc(n) + "</span>"; }).join("");
  });
})();
